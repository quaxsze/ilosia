#!/bin/sh
set -eu

if [ "$#" -ne 1 ]; then
  echo "Usage: $0 <verified-keycloak-username>" >&2
  exit 2
fi

username=$1
namespace=warpgate
keycloak_namespace=ilosia
client_id=warpgate-aw0
provider_name=keycloak-aw0
redirect_uri=https://localhost:8888/@warpgate/api/sso/return
backchannel_uri=https://warpgate.warpgate.svc.cluster.local:8888/@warpgate/api/sso/providers/keycloak-aw0/backchannel-logout
issuer=http://keycloak.localhost:8080/realms/ilosia
config_file=$(mktemp)
client_file=$(mktemp)
trap 'rm -f "$config_file" "$client_file"' EXIT INT TERM
umask 077

keycloak_pod=$(kubectl get pod --namespace "$keycloak_namespace" \
  --selector app.kubernetes.io/name=keycloak \
  --field-selector=status.phase=Running \
  --output=jsonpath='{.items[0].metadata.name}')
[ -n "$keycloak_pod" ] || {
  echo "No running Keycloak Pod found in namespace $keycloak_namespace." >&2
  exit 1
}

admin_username=$(kubectl get secret ilosia-secrets --namespace "$keycloak_namespace" \
  --output='go-template={{with index .data "KEYCLOAK_ADMIN_USERNAME"}}{{. | base64decode}}{{end}}')
admin_username=${admin_username:-admin}
admin_password=$(kubectl get secret ilosia-secrets --namespace "$keycloak_namespace" \
  --output='go-template={{index .data "KEYCLOAK_ADMIN_PASSWORD" | base64decode}}')

kcadm() {
  kubectl exec --stdin --namespace "$keycloak_namespace" "$keycloak_pod" -- \
    /opt/keycloak/bin/kcadm.sh "$@" \
    --no-config --server http://127.0.0.1:8080 --realm master \
    --user "$admin_username" --password "$admin_password"
}

if ! kcadm get realms/master >/dev/null; then
  cat >&2 <<'EOF'
Keycloak rejected the permanent administrator credentials stored in
ilosia-secrets. Repair the local administrator with:
  ./scripts/recover_local_keycloak_admin.sh
EOF
  exit 1
fi

# These are realm invariants required by the Agent Workspace identity model.
kcadm update realms/ilosia \
  -s duplicateEmailsAllowed=false \
  -s verifyEmail=true \
  -s loginWithEmailAllowed=true >/dev/null

users=$(kcadm get users -r ilosia --query "username=$username")
user_count=$(printf '%s' "$users" | jq --arg username "$username" \
  '[.[] | select(.username == $username)] | length')
if [ "$user_count" -ne 1 ]; then
  echo "Expected exactly one Keycloak user named $username, found $user_count." >&2
  exit 1
fi
email=$(printf '%s' "$users" | jq --exit-status --raw-output --arg username "$username" \
  '.[] | select(.username == $username and .enabled == true and .emailVerified == true) | .email | select(length > 0)') || {
  echo "Keycloak user $username must be enabled and have a verified email." >&2
  exit 1
}

if kubectl get secret warpgate-aw0-oidc --namespace "$namespace" >/dev/null 2>&1; then
  client_secret=$(kubectl get secret warpgate-aw0-oidc --namespace "$namespace" \
    --output='go-template={{index .data "clientSecret" | base64decode}}')
else
  client_secret=$(openssl rand -hex 32)
fi

jq --null-input \
  --arg client_id "$client_id" \
  --arg secret "$client_secret" \
  --arg redirect_uri "$redirect_uri" \
  --arg backchannel_uri "$backchannel_uri" \
  '{
    clientId: $client_id,
    name: "Warpgate AW0",
    enabled: true,
    protocol: "openid-connect",
    publicClient: false,
    clientAuthenticatorType: "client-secret",
    secret: $secret,
    standardFlowEnabled: true,
    directAccessGrantsEnabled: false,
    serviceAccountsEnabled: false,
    redirectUris: [$redirect_uri],
    webOrigins: ["https://localhost:8888"],
    attributes: {
      "backchannel.logout.url": $backchannel_uri,
      "backchannel.logout.session.required": "true",
      "backchannel.logout.revoke.offline.tokens": "true"
    }
  }' >"$client_file"

clients=$(kcadm get clients -r ilosia --query "clientId=$client_id")
client_uuid=$(printf '%s' "$clients" | jq --raw-output --arg client_id "$client_id" \
  '[.[] | select(.clientId == $client_id)] | if length == 1 then .[0].id else empty end')
if [ -n "$client_uuid" ]; then
  kcadm update "clients/$client_uuid" -r ilosia --file - <"$client_file" >/dev/null
else
  kcadm create clients -r ilosia --file - <"$client_file" >/dev/null
fi

kubectl create secret generic warpgate-aw0-oidc \
  --namespace "$namespace" \
  --from-literal=clientSecret="$client_secret" \
  --dry-run=client --output=yaml | kubectl apply -f - >/dev/null

cat >"$config_file" <<EOF
# Generated by configure_agent_workspace_aw0_oidc.sh; stored as a Secret.
external_host: localhost
sso_providers:
  - name: $provider_name
    label: Keycloak
    auto_create_users: true
    provider:
      type: custom
      client_id: $client_id
      client_secret: $client_secret
      issuer_url: $issuer
      scopes: [openid, profile, email]
recordings:
  enable: true
  path: /data/recordings
database_url: sqlite:/data/db
ssh:
  enable: true
  listen: 0.0.0.0:2222
  external_host: localhost
  external_port: 2222
  keys: /data/ssh-keys
  host_key_verification: prompt
  inactivity_timeout: 5m
http:
  listen: 0.0.0.0:8888
  external_host: localhost
  external_port: 8888
  certificate: /data/tls.certificate.pem
  key: /data/tls.key.pem
  trust_x_forwarded_headers: false
  session_max_age: 30m
  cookie_max_age: 1day
  sni_certificates: []
kubernetes:
  enable: false
mysql:
  enable: false
postgres:
  enable: false
log:
  retention: 7days
  audit_retention: 30days
  send_to: null
  format: text
EOF

kubectl create secret generic warpgate-aw0-config \
  --namespace "$namespace" \
  --from-file=warpgate.yaml="$config_file" \
  --dry-run=client --output=yaml | kubectl apply -f - >/dev/null

helm upgrade --install warpgate \
  oci://ghcr.io/warp-tech/helm-charts/warpgate \
  --version 0.2.0 \
  --namespace "$namespace" \
  --values spikes/agent-workspace/warpgate-values.yaml \
  --values spikes/agent-workspace/warpgate-oidc-values.yaml \
  --wait --timeout 5m

# shortcut: split DNS for *.localhost is emulated through the k3d host gateway.
cluster_name=${K3D_CLUSTER_NAME:-ilosia}
if ! host_gateway=$(docker inspect "k3d-$cluster_name-server-0" | jq --exit-status --raw-output \
  '[.[0].NetworkSettings.Networks[].Gateway | select(test("^([0-9]{1,3}\\.){3}[0-9]{1,3}$"))] | first'); then
  echo "Could not find the Docker gateway for k3d-$cluster_name-server-0." >&2
  exit 1
fi
host_alias_patch=$(jq --compact-output --null-input --arg ip "$host_gateway" \
  '{spec:{template:{spec:{hostAliases:[{ip:$ip,hostnames:["keycloak.localhost"]}]}}}}')
kubectl patch deployment warpgate --namespace "$namespace" \
  --type=merge --patch "$host_alias_patch" >/dev/null

# shortcut: AW0 tests logout semantics with Warpgate's self-signed certificate.
kubectl set env deployment/keycloak --namespace "$keycloak_namespace" \
  KC_SPI_CONNECTIONS_HTTP_CLIENT__DEFAULT__DISABLE_TRUST_MANAGER=true >/dev/null
kubectl rollout status deployment/keycloak --namespace "$keycloak_namespace" --timeout=5m
kubectl rollout status deployment/warpgate --namespace "$namespace" --timeout=5m

./scripts/start_agent_workspace_aw0_ssh_proxy.sh

WARPGATE_AW0_SSO_USERNAME="$username" \
  ./scripts/configure_agent_workspace_aw0_warpgate.sh

cat <<EOF

Keycloak OIDC is configured for $username ($email).
Open https://localhost:8888/@warpgate and choose Keycloak.
EOF
